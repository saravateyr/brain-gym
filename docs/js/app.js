// ---------------------------------------------------------------- Storage
const Store = {
  key: 'std4-brain-gym-v1',
  d: {},
  load() {
    try { this.d = JSON.parse(localStorage.getItem(this.key)) || {}; } catch (e) { this.d = {}; }
    this.d.best = this.d.best || {};
    this.d.mocks = this.d.mocks || [];
    if (this.d.sound === undefined) this.d.sound = true;
  },
  save() { try { localStorage.setItem(this.key, JSON.stringify(this.d)); } catch (e) { /* storage unavailable */ } },
};
const starsFor = (score, total) => { const p = score / total; return p >= 0.9 ? 3 : p >= 0.7 ? 2 : p >= 0.5 ? 1 : 0; };
const bestOf = (id, lv) => Store.d.best[`${id}-${lv}`] || null; // {score,total,stars}
const catStars = id => [1, 2, 3].reduce((s, lv) => s + ((bestOf(id, lv) || {}).stars || 0), 0);
const unlocked = (id, lv) => lv === 1 || ((bestOf(id, lv - 1) || {}).stars || 0) >= 1;
const catsOf = sec => Object.values(GEN).filter(g => g.section === sec);
const starStr = (n, max) => '★'.repeat(n) + '☆'.repeat(max - n);

// ---------------------------------------------------------------- Sound
const Sound = {
  ctx: null,
  play(kind) {
    if (!Store.d.sound) return;
    try {
      this.ctx = this.ctx || new (window.AudioContext || window.webkitAudioContext)();
      const notes = kind === 'good' ? [523, 659, 784] : kind === 'bad' ? [300, 220] : [523, 659, 784, 1047];
      notes.forEach((f, i) => {
        const o = this.ctx.createOscillator(), g = this.ctx.createGain(), t = this.ctx.currentTime + i * 0.11;
        o.type = kind === 'bad' ? 'triangle' : 'sine'; o.frequency.value = f;
        g.gain.setValueAtTime(0.0001, t); g.gain.exponentialRampToValueAtTime(0.25, t + 0.02); g.gain.exponentialRampToValueAtTime(0.0001, t + 0.2);
        o.connect(g).connect(this.ctx.destination); o.start(t); o.stop(t + 0.22);
      });
    } catch (e) { /* audio not available */ }
  },
};

// ---------------------------------------------------------------- Question sets
function validQ(q) {
  if (!q || !Array.isArray(q.options) || q.options.length !== 4 || q.answer < 0) return false;
  const txt = q.q + q.options.join('|') + q.explain;
  return !/undefined|NaN|Infinity/.test(txt);
}
function makeSet(pairs) { // pairs: [[id, level], ...]
  const out = [], seen = new Set();
  pairs.forEach(([id, lv]) => {
    for (let tries = 0; tries < 60; tries++) {
      let q;
      try { q = GEN[id].gen(lv); } catch (e) { console.error(id, lv, e); continue; }
      if (!validQ(q)) continue;
      const key = q.q + q.visual;
      if (seen.has(key) && tries < 40) continue;
      seen.add(key); q.cat = id; q.level = lv; out.push(q); break;
    }
  });
  return out;
}

