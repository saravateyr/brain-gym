// ---------------------------------------------------------------- Router
function route() {
  const hash = location.hash.replace(/\?.*$/, '') || '#/';
  const parts = hash.replace(/^#\/?/, '').split('/').filter(Boolean);
  if (parts[0] !== 'mock' || parts[1] !== 'run') stopTimer();
  if (parts[0] !== 'p') play = null;
  switch (parts[0]) {
    case undefined: return renderHome();
    case 's': return renderSection(parts[1]);
    case 'c': return renderCategory(parts[1]);
    case 'p': return startPlay(parts[1], Number(parts[2]));
    case 'mock':
      if (parts[1] === 'run') return renderMockRun();
      if (parts[1] === 'result') return renderMockResult();
      return renderMockIntro();
    case 'settings': return renderSettings();
    default: return go('#/');
  }
}

